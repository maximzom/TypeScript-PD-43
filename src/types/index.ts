// Основні типи для всього додатку
// Цей файл містить усі інтерфейси та типи даних, які використовуються в різних модулях програми

// Експортуємо інтерфейс для стану головного додатку
// Описує структуру даних, які зберігають загальний стан програми
export interface AppState {
    currentTheme: string;  // Поточна тема інтерфейсу ('light' або 'dark')
    stats: {               // Об'єкт зі статистичними даними
        totalUsers: number;     // Загальна кількість користувачів
        totalPosts: number;     // Загальна кількість постів
        totalProducts: number;  // Загальна кількість продуктів
        avgRating: number;      // Середній рейтинг продуктів
    };
    isLoading: boolean;    // Прапорець, який вказує чи відбувається завантаження даних
}

// Експортуємо інтерфейс для даних користувача
// Описує повну структуру даних користувача, отриманих з API
export interface User {
    id: number;           // Унікальний ідентифікатор користувача
    name: string;         // Повне ім'я користувача
    username: string;     // Ім'я користувача для входу (нікнейм)
    email: string;        // Електронна пошта користувача
    address: {            // Об'єкт з адресними даними користувача
        street: string;   // Назва вулиці
        suite: string;    // Номер квартири/офісу
        city: string;     // Місто
        zipcode: string;  // Поштовий індекс
        geo: {            // Географічні координати
            lat: string;  // Широта
            lng: string;  // Довгота
        };
    };
    phone: string;        // Номер телефону користувача
    website: string;      // Веб-сайт користувача
    company: {            // Інформація про компанію користувача
        name: string;          // Назва компанії
        catchPhrase: string;   // Девіз компанії
        bs: string;            // Сфера діяльності компанії
    };
    avatar?: string;      // Необов'язкове поле - URL аватара користувача
    status?: string;      // Необов'язкове поле - статус користувача (active/inactive)
    joinDate?: string;    // Необов'язкове поле - дата приєднання у форматі рядка
}

// Експортуємо інтерфейс для стану менеджера користувачів
// Описує всі дані та налаштування, необхідні для роботи з користувачами
export interface UsersState {
    users: User[];              // Масив всіх завантажених користувачів
    filteredUsers: User[];      // Масив користувачів після застосування фільтрів
    searchQuery: string;        // Рядок пошуку для фільтрації користувачів
    statusFilter: string;       // Фільтр статусу ('all', 'active', 'inactive')
    sortBy: string;             // Критерій сортування ('name-asc', 'name-desc', тощо)
    viewMode: 'grid' | 'list';  // Режим відображення - сітка або список
    currentTheme: string;       // Поточна тема інтерфейсу
    isLoading: boolean;         // Прапорець завантаження даних
}

// Експортуємо інтерфейс для даних поста
// Описує структуру поста блогу або новини
export interface Post {
    userId: number;     // ID автора поста (зв'язок з користувачем)
    id: number;         // Унікальний ідентифікатор поста
    title: string;      // Заголовок поста
    body: string;       // Основний текст поста
    category?: string;  // Необов'язкове поле - категорія поста
    tags?: string[];    // Необов'язкове поле - масив тегів поста
    createdAt?: string; // Необов'язкове поле - дата створення у форматі рядка
    likes?: number;     // Необов'язкове поле - кількість вподобань
    comments?: number;  // Необов'язкове поле - кількість коментарів
    readTime?: number;  // Необов'язкове поле - час читання в хвилинах
    featured?: boolean; // Необов'язкове поле - чи є пост рекомендованим
}

// Експортуємо інтерфейс для автора поста
// Спрощена версія User для відображення інформації про автора
export interface Author {
    id: number;        // Унікальний ідентифікатор автора
    name: string;      // Повне ім'я автора
    username: string;  // Нікнейм автора
    email: string;     // Електронна пошта автора
    avatar?: string;   // Необов'язкове поле - URL аватара автора
}

// Експортуємо інтерфейс для стану менеджера постів
// Описує всі дані та налаштування, необхідні для роботи з постами
export interface PostsState {
    posts: Post[];                  // Масив всіх завантажених постів
    filteredPosts: Post[];          // Масив постів після застосування фільтрів
    users: Author[];                // Масив авторів постів
    searchQuery: string;            // Рядок пошуку для фільтрації постів
    categoryFilter: string;         // Фільтр категорії ('all', 'Technology', тощо)
    sortBy: string;                 // Критерій сортування ('newest', 'oldest', тощо)
    featuredOnly: boolean;          // Прапорець "показувати тільки рекомендовані"
    viewMode: 'card' | 'compact';   // Режим відображення - картки або компактний
    currentTheme: string;           // Поточна тема інтерфейсу
    isLoading: boolean;             // Прапорець завантаження даних
}

// Експортуємо інтерфейс для даних фотографії/продукту
// Описує структуру фотографії з API та додаткові поля для функціоналу магазину
export interface Photo {
    albumId: number;          // ID альбому, до якого належить фотографія
    id: number;               // Унікальний ідентифікатор фотографії
    title: string;            // Заголовок фотографії
    url: string;              // URL повнорозмірного зображення
    thumbnailUrl: string;     // URL мініатюрного зображення
    category?: string;        // Необов'язкове поле - категорія продукту
    price?: number;           // Необов'язкове поле - ціна продукту
    rating?: number;          // Необов'язкове поле - рейтинг продукту
    reviews?: number;         // Необов'язкове поле - кількість відгуків
    description?: string;     // Необов'язкове поле - опис продукту
    inStock?: boolean;        // Необов'язкове поле - чи є продукт в наявності
    features?: string[];      // Необов'язкове поле - масив характеристик
    tags?: string[];          // Необов'язкове поле - масив тегів
}

// Експортуємо інтерфейс для стану галереї продуктів
// Описує всі дані та налаштування, необхідні для роботи з галереєю продуктів
export interface GalleryState {
    products: Photo[];        // Масив всіх завантажених продуктів
    filteredProducts: Photo[]; // Масив продуктів після застосування фільтрів
    searchQuery: string;      // Рядок пошуку для фільтрації продуктів
    categoryFilter: string;   // Фільтр категорії ('all', 'Electronics', тощо)
    priceFilter: string;      // Фільтр ціни ('all', '0-100', '100-500', тощо)
    sortBy: string;           // Критерій сортування ('name-asc', 'price-desc', тощо)
    inStockOnly: boolean;     // Прапорець "показувати тільки в наявності"
    maxPrice: number;         // Максимальна ціна для фільтрації
    currentTheme: string;     // Поточна тема інтерфейсу
    isLoading: boolean;       // Прапорець завантаження даних
}