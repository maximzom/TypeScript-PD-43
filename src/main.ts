// Головний файл, який об'єднує всі модулі додатку
// Цей файл є точкою входу програми та відповідає за ініціалізацію всіх менеджерів

// Імпортуємо клас AppManager з модуля головного додатку
// Цей менеджер відповідає за загальний функціонал головної сторінки
import { AppManager } from './modules/app/AppManager.js';

// Імпортуємо клас UsersManager з модуля користувачів
// Цей менеджер відповідає за функціонал сторінки користувачів
import { UsersManager } from './modules/users/UsersManager.js';

// Імпортуємо модуль постів без прямого доступу до класу
// Цей імпорт виконує код із файлу PostsManager.js, який автоматично створює глобальний екземпляр
import './modules/posts/PostsManager.js';

// Імпортуємо модуль галереї без прямого доступу до класу
// Цей імпорт виконує код із файлу GalleryManager.js, який автоматично створює глобальний екземпляр
import './modules/gallery/GalleryManager.js';

// Додаємо обробник події, який викликається коли весь HTML документ повністю завантажений та розпарсений
// Це гарантує, що всі елементи DOM доступні для маніпуляцій
document.addEventListener('DOMContentLoaded', () => {
    // Отримуємо шлях поточної сторінки з об'єкта window.location
    // Наприклад: "/index.html" або "/users.html"
    const path = window.location.pathname;
    
    // Отримуємо ім'я файлу поточної сторінки
    // split('/') розбиває шлях на частини по слешам
    // pop() бере останній елемент масиву (ім'я файлу)
    // || '' - забезпечує значення за замовчуванням на випадок порожнього результату
    const page = path.split('/').pop() || '';
    
    // Виводимо в консоль інформацію про ініціалізацію для поточної сторінки
    // Це допомагає при налагодженні та розумінні того, яка сторінка завантажується
    console.log('Initializing app for page:', page);
    
    // Перевіряємо чи поточна сторінка є головною сторінкою
    // Умова охоплює три варіанти:
    // - page === 'index.html' - явне ім'я файлу
    // - page === '' - коренева сторінка без імені файлу
    // - page.endsWith('/') - сторінка, яка закінчується слешем (часто коренева)
    if (page === 'index.html' || page === '' || page.endsWith('/')) {
        // Створюємо новий екземпляр AppManager для головної сторінки
        // Цей менеджер ініціалізує всі компоненти головної сторінки
        new AppManager();
        // Логуємо успішну ініціалізацію для відладки
        console.log('AppManager initialized');
    } 
    // Перевіряємо чи поточна сторінка є сторінкою користувачів
    else if (page === 'users.html') {
        // Створюємо новий екземпляр UsersManager для сторінки користувачів
        // Цей менеджер ініціалізує всі компоненти сторінки користувачів
        new UsersManager();
        // Логуємо успішну ініціалізацію для відладки
        console.log('UsersManager initialized');
    }
    // Для сторінок posts.html та gallery.html менеджери створюються автоматично через імпорт вище
    // Це відбувається тому, що в цих модулях є код, який створює глобальні екземпляри при імпорті
    // Наприклад: (window as any).postsManager = new PostsManager();
});

// Експортуємо класи AppManager та UsersManager для можливості їх імпорту в інших модулях
// Це дозволяє використовувати ці класи в інших частинах програми, якщо це буде необхідно
export { AppManager, UsersManager };